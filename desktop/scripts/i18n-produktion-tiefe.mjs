/** Block prefix used to slot a key next to its existing siblings. */
function blockPrefix(key) {
  const parts = key.split('.')
  return parts.slice(0, Math.min(2, parts.length - 1)).join('.') + '.'
}

for (const locale of ['de', 'en', 'fr', 'it']) {
  const file = join(root, `${locale}.json`)
  // Preserve the file's existing key order (JSON.parse keeps insertion order
  // for string keys) — a global re-sort would move ~2k untouched lines and
  // poison every future merge.
  const data = JSON.parse(readFileSync(file, 'utf8'))
  const entries = Object.entries(data)

  let removed = 0
  for (const key of DEAD_KEYS) {
    const idx = entries.findIndex(([k]) => k === key)
    if (idx >= 0) { entries.splice(idx, 1); removed++ }
  }

  let added = 0
  let updated = 0
  for (const [key, value] of Object.entries(NEW_KEYS[locale])) {
    const existing = entries.findIndex(([k]) => k === key)
    if (existing >= 0) {
      entries[existing][1] = value
      updated++
      continue
    }
    // Insert alphabetically inside the key's own block (e.g.
    // "produktion.settings."); brand-new sub-blocks fall back to the
    // top-level block ("produktion.") so they stay in the module section.
    let insertAt = -1
    for (const prefix of [blockPrefix(key), key.split('.')[0] + '.']) {
      let lastBlockIdx = -1
      for (let i = 0; i < entries.length; i++) {
        const k = entries[i][0]
        if (k.startsWith(prefix)) {
          lastBlockIdx = i
          if (insertAt === -1 && k > key) insertAt = i
        }
      }
      if (insertAt === -1 && lastBlockIdx >= 0) insertAt = lastBlockIdx + 1
      if (insertAt !== -1) break
    }
    if (insertAt === -1) insertAt = entries.length
    entries.splice(insertAt, 0, [key, value])
    added++
  }

  writeFileSync(file, JSON.stringify(Object.fromEntries(entries), null, 2) + '\n', 'utf8')
  console.log(`${locale}: +${added} added, ~${updated} updated, -${removed} removed`)
}
