for (const [lang, entries] of Object.entries(T)) {
  const file = resolve(dir, `${lang}.json`)
  const json = JSON.parse(readFileSync(file, 'utf8'))
  let added = 0
  for (const [k, v] of Object.entries(entries)) {
    if (!(k in json)) added++
    json[k] = v
  }
  // preserve existing key order (file is not sorted); new keys append at end
  writeFileSync(file, JSON.stringify(json, null, 2) + '\n', 'utf8')
  console.log(`${lang}: +${added} keys (total ${Object.keys(json).length})`)
}
